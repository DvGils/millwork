// Writes the bundle's icon table into the Python package, so a component
// refuses an icon name the tab could not draw. Runs as part of the build; the
// Python tests compare the two and fail when they drift.
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const source = readFileSync(resolve(here, "../src/icons.ts"), "utf8");
const table = source.match(/const byPascal[^{]*\{([^}]*)\}/);
if (!table) throw new Error("icons.ts: no byPascal table");
const names = table[1]
  .split(",")
  .map((n) => n.trim())
  .filter(Boolean);

const lines = [
  '"""The icons the bundle ships, by their lucide names. Generated by',
  "``bundle/scripts/icons.mjs`` from ``bundle/src/icons.ts``; not edited by hand.",
  '"""',
  "",
  "PASCAL: tuple[str, ...] = (",
  ...names.map((n) => `    "${n}",`),
  ")",
  "",
];
writeFileSync(resolve(here, "../../src/millwork/_icons.py"), lines.join("\n"));
console.log(`icons: ${names.length} names written to src/millwork/_icons.py`);
