// Kebab-case names ("file-text", "chevron-down"), the way the catalogue's
// `icon` prop and lucide's own docs spell them.
const byKebab: Record<string, LucideIcon> = {};
for (const [name, icon] of Object.entries(byPascal)) {
  const kebab = name
    .replace(/([a-z0-9])([A-Z])/g, "$1-$2")
    .replace(/([A-Z])([A-Z][a-z])/g, "$1-$2")
    .replace(/([a-z])([0-9])/g, "$1-$2")
    .toLowerCase();
  byKebab[kebab] = icon;
  // "trash2" as well as lucide's "trash-2".
  byKebab[kebab.replace(/-([0-9])/g, "$1")] = icon;
}

export function icon(name: unknown): LucideIcon | null {
  if (typeof name !== "string" || !name) return null;
  const found = byKebab[name] ?? byPascal[name];
  if (!found) console.warn(`millwork: unknown icon "${name}"`);
  return found ?? null;
}

// What `import { Search } from "lucide-react"` resolves to in a custom component.
export const lucideSubset: Record<string, unknown> = { ...byPascal };
